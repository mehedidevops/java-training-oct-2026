package com.syntexpro.students.basic.datatype;

public class DataType {

    //main
    //psvm

    public static void main(String[] args) {

        // Java 2 types
        //1. primitive
        //2. non primitive

        //1 primitive: 8 types
        //1. byte
        byte rafi = -127;
        System.out.println("Hello World");

        int rafii = 1;
        System.out.println(rafi);

        //2. short
        //3. int  ***
        //4. long ***
        long accountBalance = 10L;
        System.out.println(accountBalance);

        //5. float
        float rafis1 = 1.1234567890123456F;
        System.out.println(rafis1);
        //6. double
        double rafis2 = 1.1234567890123456;  //*****
        System.out.println(rafis2);

        //7. char
        char rafis3 = '*';
        System.out.println(rafis3);

        //8. boolean

        boolean rafis = true;
        System.out.println(rafis);

        //2. non primitive
        //Class, Array, String ....


    }


}
