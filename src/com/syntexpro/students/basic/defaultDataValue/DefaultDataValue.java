package com.syntexpro.students.basic.defaultDataValue;

public class DefaultDataValue {

    int a;
    double b;
    boolean c;
    char d;

    public static void main(String[] args) {

        DefaultDataValue defaultDataValue = new DefaultDataValue();
        System.out.println("byte,short,int & long No value getting any place = " + defaultDataValue.a);
        System.out.println("float & double No value getting any place = " + defaultDataValue.b);
        System.out.println("boolean No value getting any place = " + defaultDataValue.c);
        System.out.println("char No value getting any place = " + defaultDataValue.d);

    }



}
